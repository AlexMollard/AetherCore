"""Generate the deliberately small FFI surface and reject C#/native declaration drift."""
import argparse
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
HERE = pathlib.Path(__file__).resolve().parent
TYPES = {
    "void": ("void", "()", "void", "void"),
    "u32": ("uint32_t", "u32", "std::uint32_t", "uint"),
    "i32": ("int32_t", "i32", "std::int32_t", "int"),
    "vec3": ("AetherGameplayVec3", "AetherGameplayVec3", "Vec3", "Vector3"),
}


def validated_functions(manifest):
    if manifest.get("schemaVersion") != 1 or manifest.get("abiMajor") != 1:
        raise ValueError("Unsupported engine-call manifest version")
    names = set()
    functions = manifest.get("functions", [])
    if not functions:
        raise ValueError("An empty engine-call surface is not a parity check")
    for function in functions:
        name = function["name"]
        if not re.fullmatch(r"aether_[a-z0-9_]+", name) or name in names:
            raise ValueError(f"Invalid or duplicate export: {name}")
        names.add(name)
        if function["result"] not in TYPES:
            raise ValueError(f"Unknown result type for {name}")
        params = set()
        for param in function["params"]:
            if not re.fullmatch(r"[a-zA-Z][a-zA-Z0-9]*", param["name"]) or param["name"] in params or param["type"] not in TYPES or param["type"] == "void":
                raise ValueError(f"Invalid parameter for {name}")
            params.add(param["name"])
    return functions


def check_parity(manifest, root):
    native = (root / manifest["nativeSource"]).read_text(encoding="utf-8")
    managed = (root / manifest["managedSource"]).read_text(encoding="utf-8")
    for function in validated_functions(manifest):
        name = function["name"]
        for source, prefix, language in [(native, r"AE_SCRIPT_API", 2), (managed, r"internal\s+static\s+partial", 3)]:
            match = re.search(prefix + r"\s+([\w:]+)\s+" + name + r"\s*\(([^)]*)\)", source)
            expected = TYPES[function["result"]][language]
            if not match or match[1] != expected:
                raise ValueError(f"{name}: result differs from manifest ({expected})")
            actual_params = [item.strip().split()[0] for item in match[2].split(",") if item.strip()]
            if actual_params != [TYPES[param["type"]][language] for param in function["params"]]:
                raise ValueError(f"{name}: parameters differ from manifest")


def render_calls(manifest):
    c = ['// Generated by tools/gameplay-api/generate.py. Do not edit.', '#pragma once', '#include "scripting/GameplayAbi.h"', '#ifdef __cplusplus', 'extern "C" {', '#endif']
    rust = ['// Generated legacy raw exports; callers must obey engine context/lifetime rules.', 'use super::gameplay_abi::AetherGameplayVec3;', 'unsafe extern "C" {']
    for function in validated_functions(manifest):
        name = function["name"]
        cparams = ", ".join(f'{TYPES[p["type"]][0]} {p["name"]}' for p in function["params"]) or "void"
        rparams = ", ".join(f'{p["name"]}: {TYPES[p["type"]][1]}' for p in function["params"])
        c.append(f'{TYPES[function["result"]][0]} {name}({cparams});')
        rust.append(f'    pub fn {name}({rparams}) -> {TYPES[function["result"]][1]};')
    c.extend(['#ifdef __cplusplus', '}', '#endif', ''])
    rust.extend(['}', ''])
    return "\n".join(c), "\n".join(rust)


def rust_type(ctype):
    ctype = " ".join(ctype.split())
    if ctype.endswith("*"):
        base = ctype[:-1].strip()
        const = base.startswith("const ")
        return ("*const " if const else "*mut ") + rust_type(base.removeprefix("const "))
    return {"uint32_t": "u32", "int32_t": "i32", "uint64_t": "u64", "int64_t": "i64", "float": "f32", "char": "core::ffi::c_char", "void": "()"}.get(ctype, ctype)


def rust_ident(name):
    keywords = {"type", "match", "loop", "ref", "self", "mod", "move", "use", "pub", "fn", "const", "static", "crate", "super", "async", "await", "dyn", "in", "where", "impl", "trait", "enum", "struct", "union", "return", "let", "mut", "unsafe", "extern"}
    return "r#" + name if name in keywords else name


def rust_params(params):
    if params.strip() in ("", "void"):
        return ""
    result = []
    for param in params.split(","):
        match = re.fullmatch(r"(.*?)\b([A-Za-z_]\w*)", param.strip())
        if not match:
            raise ValueError(f"Unsupported ABI parameter: {param}")
        result.append(f"{rust_ident(match[2])}: {rust_type(match[1].strip())}")
    return ", ".join(result)


def render_abi(source):
    source = re.sub(r"//[^\n]*", "", source)
    lines = ['// Generated from src/engine/scripting/GameplayAbi.h. Do not edit.', '#![allow(non_snake_case, dead_code)]']
    for name, value in re.findall(r"#define\s+(AE_GAMEPLAY_\w+)\s+([^\n]+)", source):
        value = value.strip()
        wide = re.fullmatch(r"UINT64_C\((\d+)\)", value)
        if wide:
            kind, number = "u64", wide[1]
        elif re.fullmatch(r"\d+u?", value):
            kind, number = ("u32" if value.endswith("u") else "i32"), value.rstrip("u")
        else:
            raise ValueError(f"Unsupported ABI constant: {name}")
        lines.append(f"pub const {name}: {kind} = {number};")
    for base, name in re.findall(r"typedef\s+(\w+)\s+(Aether\w+);", source):
        lines.append(f"pub type {name} = {rust_type(base)};")
    for name, fields, alias in re.findall(r"typedef struct (\w+)\s*\{(.*?)\}\s*(\w+);", source, re.S):
        if name != alias:
            raise ValueError("ABI struct tags must equal typedef names")
        lines.extend(['#[repr(C)]', '#[derive(Clone, Copy)]', f'pub struct {name} {{'])
        for field in fields.split(";"):
            field = field.strip()
            if not field:
                continue
            callback = re.fullmatch(r"(.*?)\(\*(\w+)\)\((.*?)\)", field, re.S)
            array = re.fullmatch(r"(\w+)\s+(\w+)\[(\d+)\]", field)
            scalar = re.fullmatch(r"(.*?)\b(\w+)", field)
            if callback:
                lines.append(f'    pub {rust_ident(callback[2])}: Option<unsafe extern "C" fn({rust_params(callback[3])}) -> {rust_type(callback[1].strip())}>,')
            elif array:
                lines.append(f'    pub {rust_ident(array[2])}: [{rust_type(array[1])}; {array[3]}],')
            elif scalar:
                lines.append(f'    pub {rust_ident(scalar[2])}: {rust_type(scalar[1].strip())},')
            else:
                raise ValueError(f"Unsupported ABI field: {field}")
        lines.append('}')
    for result, name, params in re.findall(r"typedef\s+(\w+)\s+\(\*(\w+)\)\((.*?)\);", source):
        lines.append(f'pub type {name} = Option<unsafe extern "C" fn({rust_params(params)}) -> {rust_type(result)}>;')
    lines.extend(['unsafe extern "C" {', '    pub fn aether_gameplay_query(requestedMajor: u32, outSize: u32, outApi: *mut AetherGameplayModuleApi) -> AetherGameplayStatus;', '}', ''])
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if declarations or checked C# exports drift")
    args = parser.parse_args()
    manifest = json.loads((HERE / "engine-calls.json").read_text())
    check_parity(manifest, ROOT)
    c, rust = render_calls(manifest)
    outputs = {
        ROOT / "src/engine/scripting/generated/GameplayEngineCalls.h": c,
        HERE / "generated/engine_calls.rs": rust,
        HERE / "generated/gameplay_abi.rs": render_abi((ROOT / "src/engine/scripting/GameplayAbi.h").read_text()),
    }
    for filename, contents in outputs.items():
        if args.check:
            if not filename.exists() or filename.read_text() != contents:
                raise ValueError(f"Generated declaration drift: {filename.relative_to(ROOT)}")
        else:
            filename.parent.mkdir(parents=True, exist_ok=True)
            filename.write_text(contents, encoding="utf-8", newline="\r\n")
    print(json.dumps({"schemaVersion": 1, "status": "passed", "exports": len(manifest["functions"]), "check": args.check}))


if __name__ == "__main__":
    main()
