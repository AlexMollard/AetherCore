		// Increment when importer behavior/default settings change without a format bump.
		constexpr std::uint32_t kModelBakeRevision = 1;
		constexpr std::size_t kMaxReceiptEntries = 100000;

		struct Fingerprint
		{
			std::string path;
			bool exists = false;
			std::uint64_t size = 0;
			std::uint64_t hash = 0;
			bool owned = false; // only generated bytes created by this writer are replaceable
			bool operator==(const Fingerprint&) const = default;
		};

		struct Receipt
		{
			std::string model;
			std::vector<Fingerprint> inputs;
			std::vector<Fingerprint> outputs;
		};

		std::string Signature()
		{
			return "AE-MODEL-BAKE-" + std::to_string(kModelBakeRevision) + ":" + std::to_string(PAK_PIPELINE_VERSION) + ":" + std::to_string(MESH_VERSION) + ":" + std::to_string(SKEL_VERSION) + ":" +
			       std::to_string(ANIM_VERSION) + ":" + std::to_string(ASET_VERSION) + ":" + std::to_string(MATL_VERSION) + ":default";
		}

		std::string RelativePath(const fs::path& path, const fs::path& root)
		{
			return PathUtf8(fs::absolute(path).lexically_normal().lexically_relative(fs::absolute(root).lexically_normal()));
		}

		bool SameOutputPath(const std::string& first, const std::string& second, const fs::path& root)
		{
			if (first == second)
			{
				return true;
			}
			const auto firstPath = (root / Utf8Path(first)).lexically_normal();
			const auto secondPath = (root / Utf8Path(second)).lexically_normal();
#ifdef _WIN32
			// Compare even absent outputs: two glTF materials can collide by case
			// before either file exists. Windows ordinal folding also handles Unicode.
			if (CompareStringOrdinal(firstPath.c_str(), -1, secondPath.c_str(), -1, TRUE) == CSTR_EQUAL)
			{
				return true;
			}
#endif
			std::error_code ec;
			return fs::equivalent(firstPath, secondPath, ec) && !ec;
		}

		bool IsOutputPath(const std::string& path)
		{
			const auto relative = Utf8Path(path);
			if (relative.empty() || relative.is_absolute() || relative.has_root_path())
			{
				return false;
			}
			for (const auto& part : relative)
			{
				if (part == "..")
				{
					return false;
				}
			}
			return true;
		}

		fs::path ReceiptPath(const fs::path& model, const fs::path& root)
		{
			return root / ".aether/model-bakes" / Utf8Path(RelativePath(model, root) + ".receipt");
		}

		fs::path PendingReceiptPath(const fs::path& model, const fs::path& root)
		{
			return root / ".aether/model-bakes/pending" / Utf8Path(RelativePath(model, root) + ".receipt");
		}

		bool ReadFingerprint(const fs::path& root, Fingerprint& entry, bool required)
		{
			const auto path = root / Utf8Path(entry.path);
			std::error_code ec;
			entry.exists = fs::is_regular_file(path, ec);
			entry.size = 0;
			entry.hash = 0;
			if (!entry.exists)
			{
				std::error_code existsError;
				if (fs::exists(path, existsError))
				{
					return false;
				}
				// Absence is meaningful for optional override candidates; IO failures are not.
				return !required && (!ec || ec == std::errc::no_such_file_or_directory || ec == std::errc::not_a_directory);
			}
			ByteBuffer bytes;
			if (!ReadWholeFile(path, bytes))
			{
				return false;
			}
			entry.size = bytes.size();
			entry.hash = XXH3_64bits(bytes.data(), bytes.size());
			return true;
		}

		bool CollectInputs(const fs::path& model, const fs::path& root, std::vector<Fingerprint>& inputs)
		{
			std::vector<std::pair<fs::path, bool>> paths{{model, true}};
			for (const auto& path : MeshProcessor::CollectExternalSourceFiles(model))
			{
				paths.emplace_back(path, true);
			}
			for (const auto& path : MeshProcessor::CollectMaterialOverrideFiles(model, root))
			{
				paths.emplace_back(path, false);
			}
			for (const auto& [path, required] : paths)
			{
				Fingerprint entry{.path = RelativePath(path, root)};
				if (!ReadFingerprint(root, entry, required))
				{
					return false;
				}
				inputs.push_back(std::move(entry));
			}
			std::sort(inputs.begin(), inputs.end(), [](const Fingerprint& a, const Fingerprint& b) { return a.path < b.path; });
			inputs.erase(std::unique(inputs.begin(), inputs.end()), inputs.end());
			return true;
		}

		bool ReadReceipt(const fs::path& path, Receipt& receipt, bool requireCurrent = true)
		{
			std::ifstream input(path, std::ios::binary);
			std::string signature;
			if (!(input >> std::quoted(signature) >> std::quoted(receipt.model)) || !signature.starts_with("AE-MODEL-BAKE-") || (requireCurrent && signature != Signature()) || !IsOutputPath(receipt.model))
			{
				return false;
			}
			for (auto* entries : {&receipt.inputs, &receipt.outputs})
			{
				std::size_t count = 0;
				if (!(input >> count) || count > kMaxReceiptEntries)
				{
					return false;
				}
				for (std::size_t i = 0; i < count; ++i)
				{
					Fingerprint entry;
					if (!(input >> std::quoted(entry.path) >> entry.exists >> entry.size >> entry.hash >> entry.owned) || (entries == &receipt.outputs && (!entry.exists || !IsOutputPath(entry.path))))
					{
						return false;
					}
					entries->push_back(std::move(entry));
				}
			}
			input >> std::ws;
			return input.eof() && !receipt.inputs.empty() && !receipt.outputs.empty();
		}

		bool WriteBytes(const fs::path& path, const ByteBuffer& bytes, const fs::path& root, std::string& error)
		{
			static std::atomic<std::uint64_t> sequence{0};
			const auto staging = root / ".aether/model-bakes/staging";
			std::error_code ec;
			fs::create_directories(staging, ec);
			if (!ec)
			{
				fs::create_directories(path.parent_path(), ec);
			}
			const auto temporary = staging / (std::to_string(std::chrono::steady_clock::now().time_since_epoch().count()) + "-" + std::to_string(sequence.fetch_add(1)) + ".tmp");
			if (!ec)
			{
				std::ofstream output(temporary, std::ios::binary | std::ios::trunc);
				output.write(reinterpret_cast<const char*>(bytes.data()), static_cast<std::streamsize>(bytes.size()));
				output.flush();
				const bool wrote = static_cast<bool>(output);
				output.close();
				if (wrote && output)
				{
					fs::rename(temporary, path, ec);
					if (!ec)
					{
						return true;
					}
				}
			}
			std::error_code ignored;
			fs::remove(temporary, ignored);
			error = "cannot atomically write '" + PathUtf8(path) + "'" + (ec ? ": " + ec.message() : "");
			return false;
		}

		bool CanReplaceMaterial(const Fingerprint& existing, const Receipt& previous, const Receipt& pending, const fs::path& model, const fs::path& root)
		{
			const auto owns = [&](const Receipt& candidate)
			{
				return std::any_of(candidate.outputs.begin(), candidate.outputs.end(), [&](const Fingerprint& output)
				{
					return SameOutputPath(output.path, existing.path, root) && output.owned && output.hash == existing.hash && output.size == existing.size;
				});
			};
			if (!owns(previous) && !owns(pending))
			{
				return false;
			}
			std::error_code ec;
			for (fs::recursive_directory_iterator it(root / ".aether/model-bakes", ec), end; it != end && !ec; it.increment(ec))
			{
				if (it->path().extension() != ".receipt" || SameOutputPath(RelativePath(it->path(), root), RelativePath(ReceiptPath(model, root), root), root) || SameOutputPath(RelativePath(it->path(), root), RelativePath(PendingReceiptPath(model, root), root), root))
				{
					continue;
				}
				Receipt other;
				if (!ReadReceipt(it->path(), other, false) || std::any_of(other.outputs.begin(), other.outputs.end(), [&](const Fingerprint& output) { return SameOutputPath(output.path, existing.path, root); }))
				{
					return false; // Unknown or shared ownership never licenses destructive replacement.
				}
			}
			return !ec;
		}
