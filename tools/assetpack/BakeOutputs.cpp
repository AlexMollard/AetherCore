	bool HasCurrentModelBake(const fs::path& modelDiskPath, const fs::path& projectRoot)
	{
		if (!IsOutputPath(RelativePath(modelDiskPath, projectRoot)))
		{
			return false;
		}
		Receipt receipt;
		std::vector<Fingerprint> inputs;
		if (!ReadReceipt(ReceiptPath(modelDiskPath, projectRoot), receipt) || !SameOutputPath(receipt.model, RelativePath(modelDiskPath, projectRoot), projectRoot) || !CollectInputs(modelDiskPath, projectRoot, inputs) || inputs != receipt.inputs)
		{
			return false;
		}
		bool hasMesh = false;
		auto mesh = modelDiskPath;
		mesh.replace_extension(".mesh");
		for (const auto& output : receipt.outputs)
		{
			Fingerprint current{.path = output.path, .owned = output.owned};
			if (!ReadFingerprint(projectRoot, current, true) || current != output)
			{
				return false;
			}
			hasMesh = hasMesh || SameOutputPath(output.path, RelativePath(mesh, projectRoot), projectRoot);
		}
		return hasMesh;
	}

	BakeWriteResult WriteBakedOutputs(const MeshProcessor::ProcessedResult& baked, const fs::path& modelDiskPath, const fs::path& projectRoot)
	{
		BakeWriteResult result;
		result.meshPath = modelDiskPath;
		result.meshPath.replace_extension(".mesh");
		Receipt receipt{.model = RelativePath(modelDiskPath, projectRoot)};
		if (!IsOutputPath(receipt.model) || baked.meshData.empty() || !CollectInputs(modelDiskPath, projectRoot, receipt.inputs))
		{
			result.error = "cannot fingerprint model source/dependencies (missing or unreadable input)";
			return result;
		}
		Receipt previous;
		if (!ReadReceipt(ReceiptPath(modelDiskPath, projectRoot), previous, false) || !SameOutputPath(previous.model, receipt.model, projectRoot))
		{
			previous = {};
		}
		Receipt pending;
		if (!ReadReceipt(PendingReceiptPath(modelDiskPath, projectRoot), pending, false) || !SameOutputPath(pending.model, receipt.model, projectRoot))
		{
			pending = {};
		}
		std::vector<std::pair<fs::path, const ByteBuffer*>> outputs{{result.meshPath, &baked.meshData}};
		const auto stem = modelDiskPath.stem();
		if (!baked.skelData.empty())
		{
			outputs.emplace_back(modelDiskPath.parent_path() / (stem.string() + ".skel"), &baked.skelData);
		}
		if (!baked.animsetData.empty())
		{
			outputs.emplace_back(modelDiskPath.parent_path() / (stem.string() + ".animset"), &baked.animsetData);
		}
		for (const auto& [name, bytes] : baked.animFiles)
		{
			if (!bytes.empty())
			{
				outputs.emplace_back(projectRoot / "animations" / Utf8Path(name), &bytes);
			}
		}
		for (const auto& [name, bytes] : baked.materialFiles)
		{
			if (!bytes.empty())
			{
				outputs.emplace_back(projectRoot / Utf8Path(name), &bytes);
			}
		}

		// Complete preflight precedes ALL mutations.
		for (const auto& [path, bytes] : outputs)
		{
			Fingerprint output{.path = RelativePath(path, projectRoot), .exists = true, .size = bytes->size(), .hash = XXH3_64bits(bytes->data(), bytes->size())};
			if (!IsOutputPath(output.path))
			{
				result.error = "generated output escapes project root: " + output.path;
				return result;
			}
			const auto duplicate = std::find_if(receipt.outputs.begin(), receipt.outputs.end(), [&](const Fingerprint& entry) { return SameOutputPath(entry.path, output.path, projectRoot); });
			if (duplicate != receipt.outputs.end() && (duplicate->hash != output.hash || duplicate->size != output.size))
			{
				result.error = "conflicting generated outputs at '" + output.path + "'";
				return result;
			}
			if (path.extension() == ".material")
			{
				Fingerprint existing{.path = output.path};
				if (!ReadFingerprint(projectRoot, existing, false))
				{
					result.error = "cannot inspect existing generated material '" + output.path + "'";
					return result;
				}
				output.owned = !existing.exists || CanReplaceMaterial(existing, previous, pending, modelDiskPath, projectRoot);
				if (existing.exists && (existing.hash != output.hash || existing.size != output.size) && !output.owned)
				{
					result.error = "generated material collision at '" + output.path + "': existing bytes are shared, edited, or have no proven exclusive owner; use unique glTF material names or an authored material override";
					return result;
				}
			}
			receipt.outputs.push_back(std::move(output));
		}

		// Keep the old receipt as ownership evidence until publication succeeds. Its
		// input/output hashes reject changed or incomplete bakes, while retaining the
		// proof needed to retry replacement of an exclusively owned material.
		auto serialize = [](const Receipt& value)
		{
			std::ostringstream serialized;
			serialized << std::quoted(Signature()) << '\n' << std::quoted(value.model) << '\n';
			for (const auto* entries : {&value.inputs, &value.outputs})
			{
				serialized << entries->size() << '\n';
				for (const auto& entry : *entries)
				{
					serialized << std::quoted(entry.path) << ' ' << entry.exists << ' ' << entry.size << ' ' << entry.hash << ' ' << entry.owned << '\n';
				}
			}
			const auto text = serialized.str();
			const auto* begin = reinterpret_cast<const std::byte*>(text.data());
			return ByteBuffer(begin, begin + text.size());
		};
		const ByteBuffer receiptBytes = serialize(receipt);
		Receipt journal = receipt;
		for (const auto& output : receipt.outputs)
		{
			if (output.owned)
			{
				Fingerprint existing{.path = output.path, .owned = true};
				if (ReadFingerprint(projectRoot, existing, false) && existing.exists)
				{
					// Retain the currently owned hash too: a subsequent source edit can
					// change the next desired hash before this attempt reaches that file.
					journal.outputs.push_back(std::move(existing));
				}
			}
		}
		// A pending receipt grants ownership only for bytes already matching its hashes.
		// It is never consulted for cache hits. Keeping it across an interrupted series
		// of replacements preserves ownership of both old and newly written materials.
		if (!WriteBytes(PendingReceiptPath(modelDiskPath, projectRoot), serialize(journal), projectRoot, result.error))
		{
			return result;
		}
		for (const auto& [path, bytes] : outputs)
		{
			if (!WriteBytes(path, *bytes, projectRoot, result.error))
			{
				return result;
			}
		}
		result.ok = WriteBytes(ReceiptPath(modelDiskPath, projectRoot), receiptBytes, projectRoot, result.error);
		if (result.ok)
		{
			std::error_code ignored;
			fs::remove(PendingReceiptPath(modelDiskPath, projectRoot), ignored);
		}
		return result;
	}
